/**
 * 解析实际生成的 PAC，识别当前生成器模板并提取规则摘要。
 * 不依赖旧版注释标记，兼容历史 custom 与目前的 remote 模板。
 */
export type PacMode = "custom" | "remote" | "custom_parse_error" | "other" | "empty";

export interface PacStatusPayload {
  mode: PacMode;
  modeLabel: string;
  blockList: string[];
  directList: string[];
  pacProxy: string | null;
  remoteProxyList: string[];
  remoteDirectList: string[];
  remoteProxyCount: number;
  remoteDirectCount: number;
  notice: string;
  updatedAt: string;
  hasPac: boolean;
}

/**
 * 从压缩或未压缩的生成器代码中读取变量初始化表达式。
 * 不依赖分号、换行或声明顺序；支持 Terser 将多个 var 声明合并的输出。
 */
function readInitializer(source: string, name: string): string | null {
  const re = new RegExp("\\bvar\\s+" + name + "\\s*=");
  const match = re.exec(source);
  if (!match) return null;
  let index = match.index + match[0].length;
  while (/\\s/.test(source[index] ?? "")) index++;
  const start = index;
  const first = source[index];

  if (first === "[" || first === "{") {
    const stack: string[] = [];
    let quote = "";
    let escaped = false;
    for (; index < source.length; index++) {
      const char = source[index];
      if (quote) {
        if (escaped) escaped = false;
        else if (char === "\\\\") escaped = true;
        else if (char === quote) quote = "";
        continue;
      }
      if (char === "'" || char === '"') { quote = char; continue; }
      if (char === "[" || char === "{") stack.push(char);
      else if (char === "]" || char === "}") {
        const expected = char === "]" ? "[" : "{";
        if (stack.pop() !== expected) return null;
        if (stack.length === 0) return source.slice(start, index + 1).trim();
      }
    }
    return null;
  }

  if (first === '"' || first === "'") {
    const quote = first;
    let escaped = false;
    for (index++; index < source.length; index++) {
      const char = source[index];
      if (escaped) escaped = false;
      else if (char === "\\\\") escaped = true;
      else if (char === quote) return source.slice(start, index + 1);
    }
    return null;
  }

  index = start;
  while (index < source.length && source[index] !== ";" && source[index] !== ",") index++;
  const value = source.slice(start, index).trim();
  return value || null;
}

function parseJsArray(source: string, name: string): string[] | null {
  const raw = readInitializer(source, name);
  if (raw === null) return null;
  try {
    const parsed: unknown = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.every((item) => typeof item === "string")
      ? parsed
      : null;
  } catch {
    return null;
  }
}

function parseJsString(source: string, name: string): string | null {
  const raw = readInitializer(source, name);
  if (raw === null) return null;
  try {
    const parsed: unknown = JSON.parse(raw);
    return typeof parsed === "string" ? parsed : null;
  } catch {
    return null;
  }
}

function parseJsMap(source: string, name: string): string[] | null {
  const raw = readInitializer(source, name);
  if (raw === null) return null;
  try {
    const parsed: unknown = JSON.parse(raw);
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return null;
    const entries = Object.entries(parsed as Record<string, unknown>);
    if (entries.some(([key, value]) => !key || value !== 1)) return null;
    return [...new Set(entries.map(([key]) => key))];
  } catch {
    return null;
  }
}

function basePayload(
  mode: PacMode, modeLabel: string, updatedAt: string, hasPac: boolean, notice: string
): PacStatusPayload {
  return {
    mode, modeLabel, blockList: [], directList: [], pacProxy: null,
    remoteProxyList: [], remoteDirectList: [],
    remoteProxyCount: 0, remoteDirectCount: 0, notice, updatedAt, hasPac,
  };
}

export function parsePacStatus(pac: string, tz = "Asia/Shanghai", generatedAt: Date | null = null): PacStatusPayload {
  const updatedAt = generatedAt
    ? generatedAt.toLocaleString("zh-CN", { timeZone: tz })
    : "尚未生成";
  const hasPac = Boolean(pac.trim());

  if (!hasPac) {
    return basePayload("empty", "尚未生成 PAC", updatedAt, false,
      "还没有生成 proxy.pac。前往配置管理设置规则并生成 PAC。");
  }

  const remoteTemplate =
    /\bvar\s+proxyHosts\s*=\s*\{/.test(pac) ||
    /\bvar\s+USER_BLOCK\s*=\s*\[/.test(pac) ||
    /Generated by genpac-runner \(remote list \+ user rules\)/.test(pac);

  if (remoteTemplate) {
    const blockList = parseJsArray(pac, "USER_BLOCK");
    const directList = parseJsArray(pac, "USER_DIRECT");
    const remoteProxy = parseJsMap(pac, "proxyHosts");
    const remoteDirect = parseJsMap(pac, "remoteDirect");
    const pacProxy = parseJsString(pac, "PROXY");
    if (blockList === null || directList === null || remoteProxy === null ||
        remoteDirect === null || pacProxy === null) {
      return basePayload("custom_parse_error", "远程规则 PAC（摘要解析异常）", updatedAt, hasPac,
        "识别到远程列表模板，但无法完整读取规则摘要。仍可直接查看 PAC 文件内容；摘要解析失败不代表生成文件中的规则失效。");
    }
    return {
      ...basePayload("remote", "远程规则列表 + 自定义规则", updatedAt, hasPac,
        "自定义黑名单 " + blockList.length + " 条、自定义直连 " + directList.length +
        " 条优先生效；随后匹配远程例外直连与代理列表，其余流量直连。"),
      blockList, directList, pacProxy,
      remoteProxyList: remoteProxy,
      remoteDirectList: remoteDirect,
      remoteProxyCount: remoteProxy.length,
      remoteDirectCount: remoteDirect.length,
    };
  }

  const customTemplate =
    /\bvar\s+BLOCK_LIST\s*=\s*\[/.test(pac) ||
    /\bvar\s+DIRECT_LIST\s*=\s*\[/.test(pac) ||
    /\bvar\s+PAC_PROXY\s*=/.test(pac);
  if (customTemplate) {
    const blockList = parseJsArray(pac, "BLOCK_LIST");
    const directList = parseJsArray(pac, "DIRECT_LIST");
    const pacProxy = parseJsString(pac, "PAC_PROXY");
    if (blockList === null || directList === null || pacProxy === null) {
      return basePayload("custom_parse_error", "自定义规则 PAC（摘要解析异常）", updatedAt, hasPac,
        "识别到自定义规则模板，但无法完整读取规则变量。仍可直接查看 PAC 文件内容。");
    }
    return {
      ...basePayload("custom", "自定义规则", updatedAt, hasPac,
        "本地/内网地址优先直连；之后检查黑名单与自定义直连列表，其他请求使用默认代理：" + pacProxy),
      blockList, directList, pacProxy,
    };
  }

  return basePayload("other", "第三方或旧版 PAC 模板", updatedAt, hasPac,
    "当前文件不属于已识别的 genpac-runner 模板，因此无法可靠展示规则数量。可以打开 PAC 文件，检查其实际内容与逻辑。");
}
