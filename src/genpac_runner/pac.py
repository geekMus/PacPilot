"""PAC generation, atomic output replacement, and Webhook delivery."""
import json
import os
from pathlib import Path
import subprocess
import tempfile
import threading
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from .settings import as_bool
from .storage import get_settings, record_update

DATA_DIR = Path("/data")
PAC_PATH = DATA_DIR / "proxy.pac"
_UPDATE_LOCK = threading.Lock()


def _domain_rules(value):
    return [rule.strip() for rule in str(value or "").replace(",", "\n").splitlines() if rule.strip()]


def _custom_pac(settings):
    block_list = _domain_rules(settings["block_list"])
    direct_list = _domain_rules(settings["direct_list"])
    return '''// --------------------------------------------------
// User defined PAC (no genpac)
// Generated by genpac-runner
// --------------------------------------------------

function isMatch(host, list) {
    for (var i = 0; i < list.length; i++) {
        var rule = list[i];
        if (rule.indexOf('*') !== -1) {
            if (shExpMatch(host, rule)) return true;
        } else {
            if (host === rule || shExpMatch(host, "*." + rule)) return true;
        }
    }
    return false;
}

var BLOCK_LIST = ''' + json.dumps(block_list, ensure_ascii=True) + ''';
var DIRECT_LIST = ''' + json.dumps(direct_list, ensure_ascii=True) + ''';
var PAC_PROXY = ''' + json.dumps(settings["pac_proxy"], ensure_ascii=True) + ''';

function FindProxyForURL(url, host) {
    // 本地 / 内网地址：优先直连
    if (
        host === "localhost" ||
        host.indexOf('.') === -1 ||
        isInNet(host, "127.0.0.0", "255.0.0.0") ||
        isInNet(host, "10.0.0.0", "255.0.0.0") ||
        isInNet(host, "172.16.0.0", "255.240.0.0") ||
        isInNet(host, "192.168.0.0", "255.255.0.0")
    ) {
        return "DIRECT";
    }

    // 黑名单优先于额外直连列表
    if (BLOCK_LIST.length && isMatch(host, BLOCK_LIST)) {
        return "PROXY 0.0.0.0:0";
    }

    if (DIRECT_LIST.length && isMatch(host, DIRECT_LIST)) {
        return "DIRECT";
    }

    return PAC_PROXY;
}
'''


def _genpac_pac(settings):
    command = [
        "genpac",
        "--format=pac",
        "--pac-proxy=" + settings["pac_proxy"],
        "--gfwlist-url=" + settings["gfwlist_url"],
    ]
    if as_bool(settings["pac_compress"]):
        command.append("--pac-compress")
    if as_bool(settings["pac_precise"]):
        command.append("--pac-precise")

    completed = subprocess.run(
        command,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        timeout=180,
        check=False,
    )
    if completed.returncode:
        message = (completed.stderr or completed.stdout or "genpac 执行失败").strip()
        raise RuntimeError(message[-5000:])
    if not completed.stdout.strip():
        raise RuntimeError("genpac 执行成功，但没有生成 PAC 内容。")
    return completed.stdout


def _send_webhook(settings, success, details):
    kind = "success" if success else "failure"
    url = settings.get("webhook_" + kind + "_url", "").strip()
    if not url:
        return
    try:
        payload = json.loads(settings.get("webhook_" + kind + "_options", "{}"))
        markdown = payload.get("markdown")
        if details and isinstance(markdown, dict):
            markdown["text"] = str(markdown.get("text", "")) + "\n\n" + str(details)[:1200]
        data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        request = Request(
            url,
            data=data,
            headers={
                "Content-Type": "application/json",
                "User-Agent": "genpac-runner/0.3",
            },
            method="POST",
        )
        with urlopen(request, timeout=12) as response:
            response.read(512)
    except (OSError, ValueError, HTTPError, URLError) as error:
        print("[webhook] 发送失败：%s" % error, flush=True)


def generate_pac():
    settings = get_settings()
    mode = settings["startup_mode"]
    try:
        with _UPDATE_LOCK:
            if mode == "custom":
                content = _custom_pac(settings)
            elif mode == "genpac":
                content = _genpac_pac(settings)
            else:
                raise RuntimeError("未知的启动模式：" + mode)

            DATA_DIR.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(
                mode="w",
                encoding="utf-8",
                dir=str(DATA_DIR),
                prefix=".proxy.pac.",
                suffix=".tmp",
                delete=False,
            ) as output:
                temp_path = Path(output.name)
                output.write(content)
                output.flush()
                os.fsync(output.fileno())
            os.replace(str(temp_path), str(PAC_PATH))

        details = (
            "模式：%s；PAC 已写入 %s"
            % ("自定义 PAC" if mode == "custom" else "genpac / GFWList", PAC_PATH)
        )
        record_update("success", details)
        _send_webhook(settings, True, details)
        print("[pac] " + details, flush=True)
        return details
    except Exception as error:
        details = "PAC 更新失败：" + str(error)
        try:
            record_update("failure", details)
        except Exception as history_error:
            print("[history] 无法记录更新失败：%s" % history_error, flush=True)
        _send_webhook(settings, False, details)
        print("[pac] " + details, flush=True)
        raise
